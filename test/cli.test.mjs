for (const c of CASES) {
  test(`stats ${c.sid} agrees with skeleton`, () => {
    const sk = parsed(run('skeleton', c.file).out);
    const st = JSON.parse(run('stats', c.file).out);
    const turns = [];
    for (const o of sk) { if (o.k === 'turn') turns.push({ ch: o.ch, calls: [] }); else turns[turns.length - 1].calls.push(o); }
    const n = { turns: turns.length, prompts: turns.filter((t) => ['typed', 'sdk', 'input'].includes(t.ch)).length, calls: 0, failures: 0, unanswered: 0, errorClasses: {}, retries: 0, detours: 0, maxHops: 0, hopsOver2: 0 };
    for (const t of turns) {
      t.calls.forEach((call, i) => {
        n.calls++;
        if (call.ok === null) n.unanswered++;
        if (call.ok === false) { n.failures++; n.errorClasses[call.ek] = (n.errorClasses[call.ek] ?? 0) + 1; }
        const before = t.calls[i - 1];
        if (before && before.ok === false) { if (call.tool === before.tool) n.retries++; else n.detours++; }
      });
      // a chain: failures with one verb in a row (a failure with another verb starts a new one),
      // closed by a later success with that verb; its hops are the failures plus that success. A call
      // with no recorded result changes nothing.
      let verb = null, failures = 0;
      for (const call of t.calls) {
        if (call.ok === false) { if (call.verb === verb) failures++; else { verb = call.verb; failures = 1; } }
        else if (call.ok === true && failures && call.verb === verb) { n.maxHops = Math.max(n.maxHops, failures + 1); if (failures + 1 > 2) n.hopsOver2++; verb = null; failures = 0; }
      }
    }
    const { session, ...counts } = st;
    assert.equal(session, c.sid);
    assert.deepEqual(counts, n);
  });
}

